def run_pilot(args: argparse.Namespace) -> dict[str, Any]:
    started = time.monotonic()
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    output_paths = [output_dir / name for name in ("candidates.jsonl", "accepted.jsonl", "summary.json")]
    if not args.overwrite:
        existing = [str(path) for path in output_paths if path.exists()]
        if existing:
            raise FileExistsError(
                "Refusing to overwrite existing pilot outputs; pass --overwrite: "
                + ", ".join(existing)
            )

    selected, dataset_rows = _read_questions(args.dataset_path, args.num_questions, args.seed)
    candidate_specs: list[dict[str, Any]] = []
    for question in selected:
        for sample_index in range(args.samples_per_question):
            candidate_specs.append(
                {
                    "candidate_id": f"{question['question_id']}__sample_{sample_index}",
                    "sample_index": sample_index,
                    **question,
                }
            )

    generator = TeacherGenerator(args)
    query_prompts = [QUERY_INSTRUCTION.format(question=item["question"]) for item in candidate_specs]
    query_started = time.monotonic()
    raw_query_outputs = generator.generate(
        query_prompts, args.query_max_new_tokens, args.generation_batch_size
    )
    query_seconds = time.monotonic() - query_started
    if len(raw_query_outputs) != len(candidate_specs):
        raise RuntimeError("Teacher query generation returned the wrong number of outputs")

    queries = [extract_query(output) for output in raw_query_outputs]
    retrieval_results: list[Any | None] = [None] * len(candidate_specs)
    retrieval_errors: list[str | None] = [None] * len(candidate_specs)
    nonempty_indices = [index for index, query in enumerate(queries) if query]
    retrieval_started = time.monotonic()
    if nonempty_indices:
        try:
            batch_results, _ = _retrieve(
                args.retrieval_url,
                [queries[index] for index in nonempty_indices if queries[index] is not None],
                args.retrieval_topk,
                args.retrieval_timeout,
            )
            for index, result in zip(nonempty_indices, batch_results):
                retrieval_results[index] = result
        except Exception as exc:  # Preserve all candidates for failure analysis.
            error = f"{type(exc).__name__}: {exc}"
            for index in nonempty_indices:
                retrieval_errors[index] = error
    for index in range(len(candidate_specs)):
        if not queries[index]:
            retrieval_errors[index] = "missing_search_query"
    retrieval_seconds = time.monotonic() - retrieval_started

    information = [_passages_to_string(result) for result in retrieval_results]
    answer_prompts = [
        ANSWER_INSTRUCTION.format(
            question=item["question"],
            query=queries[index] or "",
            information=information[index],
        )
        for index, item in enumerate(candidate_specs)
    ]
    answer_started = time.monotonic()
    raw_answer_outputs = generator.generate(
        answer_prompts, args.answer_max_new_tokens, args.generation_batch_size
    )
    answer_seconds = time.monotonic() - answer_started
    if len(raw_answer_outputs) != len(candidate_specs):
        raise RuntimeError("Teacher answer generation returned the wrong number of outputs")

    records: list[dict[str, Any]] = []
    for index, item in enumerate(candidate_specs):
        raw_query = raw_query_outputs[index].strip()
        raw_answer = raw_answer_outputs[index].strip()
        format_correct, format_reasons, trajectory = validate_flat_trajectory(
            raw_query, information[index], raw_answer
        )
        extracted_answer = extract_answer(raw_answer)
        answer_correct = _answer_em(extracted_answer, item["gold_answers"])
        failure_reasons = list(format_reasons)
        if extracted_answer is None:
            failure_reasons.append("final_answer_extraction_failed")
        elif not answer_correct:
            failure_reasons.append("final_answer_em_failed")
        if retrieval_errors[index]:
            failure_reasons.append("retrieval_failed")

        records.append(
            {
                "candidate_id": item["candidate_id"],
                "question_id": item["question_id"],
                "row_index": item["row_index"],
                "question": item["question"],
                "sample_index": item["sample_index"],
                "seed": args.seed,
                "gold_answers": item["gold_answers"],
                "raw_query_output": raw_query,
                "extracted_query": queries[index],
                "retrieval_url": args.retrieval_url,
                "retrieval_topk": args.retrieval_topk,
                "retrieval_result": retrieval_results[index],
                "retrieval_error": retrieval_errors[index],
                "information": information[index],
                "raw_answer_output": raw_answer,
                "extracted_answer": extracted_answer,
                "trajectory": trajectory,
                "format_correct": format_correct,
                "answer_correct": answer_correct,
                "eligible": bool(format_correct and answer_correct),
                "format_failure_reasons": format_reasons,
                "failure_reasons": failure_reasons,
            }
        )

    expected_candidates = args.num_questions * args.samples_per_question
    if len(records) != expected_candidates:
        raise RuntimeError(
            f"Expected {expected_candidates} candidates, produced {len(records)}"
        )

    accepted = [record for record in records if record["eligible"]]
    denominator = len(records)
    format_count = sum(bool(record["format_correct"]) for record in records)
    answer_count = sum(bool(record["answer_correct"]) for record in records)
    eligible_count = len(accepted)
    reason_counts: Counter[str] = Counter()
    for record in records:
        reason_counts.update(record["failure_reasons"])

    def metric(numerator: int) -> dict[str, Any]:
        return {
            "numerator": numerator,
            "denominator": denominator,
            "rate": numerator / denominator if denominator else 0.0,
        }

    summary = {
        "status": "completed",
        "config": {
            "model_path": args.model_path,
            "dataset_path": args.dataset_path,
            "output_dir": args.output_dir,
            "num_questions": args.num_questions,
            "samples_per_question": args.samples_per_question,
            "seed": args.seed,
            "temperature": 0.7,
            "top_p": 0.9,
            "retrieval_url": args.retrieval_url,
            "retrieval_topk": args.retrieval_topk,
            "generation_batch_size": args.generation_batch_size,
            "query_max_new_tokens": args.query_max_new_tokens,
            "answer_max_new_tokens": args.answer_max_new_tokens,
            "format_filter": "exactly think/search + information + think/answer, no extra recognized tags",
            "answer_filter": "verl qa_em exact-match normalization against any golden answer",
        },
        "dataset": {
            "rows": dataset_rows,
            "selected_unique_questions": len(selected),
            "selected_question_ids": [item["question_id"] for item in selected],
        },
        "candidates": {
            "expected": expected_candidates,
            "written": len(records),
        },
        "metrics": {
            "format_correct": metric(format_count),
            "answer_correct": metric(answer_count),
            "eligible_intersection": metric(eligible_count),
        },
        "failure_reason_counts": dict(reason_counts.most_common()),
        "timing_seconds": {
            "query_generation": round(query_seconds, 3),
            "retrieval": round(retrieval_seconds, 3),
            "answer_generation": round(answer_seconds, 3),
            "total": round(time.monotonic() - started, 3),
        },
        "gpu": generator.memory_stats(),
        "infrastructure_failures": sorted(
            {record["retrieval_error"] for record in records if record["retrieval_error"]}
        ),
    }

    _write_jsonl(output_paths[0], records)
    _write_jsonl(output_paths[1], accepted)
    with output_paths[2].open("w", encoding="utf-8") as handle:
        json.dump(_json_safe(summary), handle, ensure_ascii=False, indent=2)
        handle.write("\n")
    print(json.dumps(_json_safe(summary), ensure_ascii=False, indent=2))
    return summary


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    if args.dry_run or args.self_test:
        print(json.dumps(run_self_test(), ensure_ascii=False, indent=2))
        return 0
    try:
        run_pilot(args)
    except Exception as exc:
        print(f"PILOT FAILED: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
